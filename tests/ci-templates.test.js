#!/usr/bin/env node
"use strict";

/**
 * CI template golden test.
 *
 * Renders the ci-setup templates with fixture values and asserts the output
 * is a valid, correctly-shaped workflow. Complements tests/validate-workflows.js,
 * which checks the templates statically; this one checks what they produce.
 *
 * Run: node tests/ci-templates.test.js
 */

const fs = require("fs");
const path = require("path");
const {
  TEMPLATES_ROOT,
  FIXTURE_VALUES,
  OPTIONAL_FEATURES,
  render,
  parseYaml,
  parseXml,
  hasPyYaml,
  unresolvedPlaceholders,
  stepNames,
  checkMarkers,
} = require("./lib/render-ci-templates");

let total = 0;
let passed = 0;
let failed = 0;
let skipped = 0;
const failures = [];

function test(name, condition, detail) {
  total++;
  if (condition) {
    passed++;
    return;
  }
  failed++;
  failures.push({ name, detail });
  console.log(`  FAIL: ${name}`);
  if (detail) console.log(`        ${detail}`);
}

function skip(name, reason) {
  total++;
  skipped++;
  console.log(`  SKIP: ${name} (${reason})`);
}

function section(title) {
  console.log(`\n${"=".repeat(60)}`);
  console.log(`  ${title}`);
  console.log("=".repeat(60));
}

const PLATFORMS = [
  { id: "github", template: path.join("github", "maven-ci.yml.tmpl"), namespace: "github" },
  { id: "gitea", template: path.join("gitea", "maven-ci.yml.tmpl"), namespace: "gitea" },
];

// ============================================================
// Render + structure
// ============================================================
function testRenderedWorkflows() {
  section("Rendered Workflows");

  const yamlAvailable = hasPyYaml();

  for (const platform of PLATFORMS) {
    const label = platform.id;
    const raw = fs.readFileSync(path.join(TEMPLATES_ROOT, platform.template), "utf8");

    // --- Marker integrity (must fail loudly on a malformed template) ---
    const markers = checkMarkers(raw);
    test(`${label}: optional markers are well-formed`, markers.ok, markers.error);
    if (!markers.ok) {
      // A malformed template would make every render below throw; report and move on.
      continue;
    }

    // --- Full feature set ---
    const rendered = render(platform.template, { features: ["test", "coverage", "spotbugs", "artifact"] });

    test(`${label}: no unresolved placeholders`, unresolvedPlaceholders(rendered).length === 0,
      unresolvedPlaceholders(rendered).join(", "));
    test(`${label}: keeps the generation marker`, rendered.includes("Generated by spring-boot-workflows ci-setup"));
    test(`${label}: contains no tabs`, !rendered.includes("\t"));

    if (!yamlAvailable) {
      skip(`${label}: YAML parses`, "PyYAML not available");
      continue;
    }

    const parsed = parseYaml(rendered);
    test(`${label}: YAML parses`, parsed.ok, parsed.error);
    if (!parsed.ok) continue;

    const wf = parsed.data;
    // PyYAML follows YAML 1.1 — the `on:` key becomes the boolean True.
    const triggers = wf.on !== undefined ? wf.on : wf[true];
    test(`${label}: has trigger config`, triggers !== undefined);
    test(`${label}: has jobs`, wf.jobs !== undefined && Object.keys(wf.jobs).length > 0);

    const names = stepNames(wf);
    test(`${label}: checkout step present`, names.some(n => /checkout/i.test(n)), names.join(", "));
    test(`${label}: JDK setup step present`, names.some(n => /jdk/i.test(n)));
    test(`${label}: cache step present`, names.some(n => /cache/i.test(n)));
    test(`${label}: verify step present`, names.some(n => /verify/i.test(n)));
    test(`${label}: test report step present`, names.some(n => /test report/i.test(n)));
    test(`${label}: coverage steps present`, names.some(n => /coverage/i.test(n)));
    test(`${label}: spotbugs step present`, names.some(n => /spotbugs/i.test(n)));
    test(`${label}: artifact step present`, names.some(n => /upload jar/i.test(n)));

    // --- Trigger branches ---
    const pushBranches = triggers && triggers.push && triggers.push.branches;
    const prBranches = triggers && triggers.pull_request && triggers.pull_request.branches;
    test(`${label}: push triggers on main and develop`,
      Array.isArray(pushBranches) && pushBranches.includes("main") && pushBranches.includes("develop"),
      JSON.stringify(pushBranches));
    test(`${label}: no wildcard push triggers`,
      Array.isArray(pushBranches) && pushBranches.every(b => !b.includes("*")),
      JSON.stringify(pushBranches));
    test(`${label}: pr triggers defined`, Array.isArray(prBranches) && prBranches.length > 0);

    // --- Cache path consistency ---
    const job = Object.values(wf.jobs)[0];
    const cacheStep = (job.steps || []).find(s => s.with && s.with.path);
    test(`${label}: cache path is the Maven local repository`,
      cacheStep && cacheStep.with.path === FIXTURE_VALUES["{CACHE_PATH}"],
      cacheStep ? cacheStep.with.path : "no cache step");
    test(`${label}: cache key hashes pom.xml`,
      cacheStep && cacheStep.with.key.includes("hashFiles('**/pom.xml')"));

    // --- Maven command ---
    const verifyStep = (job.steps || []).find(s => s.name && /verify/i.test(s.name));
    test(`${label}: verify uses the Maven wrapper`,
      verifyStep && verifyStep.run.includes("./mvnw"), verifyStep ? verifyStep.run : "no verify step");
    test(`${label}: verify passes the settings file`,
      verifyStep && verifyStep.run.includes("-s .mvn/settings.xml"));

    // --- Artifact path ---
    const artifactStep = (job.steps || []).find(s => s.with && s.with.name === "app");
    test(`${label}: artifact glob resolved`,
      artifactStep && artifactStep.with.path === FIXTURE_VALUES["{ARTIFACT_GLOB}"],
      artifactStep ? artifactStep.with.path : "no artifact step");

    // --- Platform namespace (comments excluded: they may mention the other token) ---
    const yamlBody = rendered.split("\n").filter(l => !l.trim().startsWith("#")).join("\n");
    if (platform.namespace === "github") {
      test(`${label}: no gitea context`, !/\$\{\{\s*gitea\./.test(yamlBody));
      test(`${label}: uses github context`, /\$\{\{\s*github\./.test(yamlBody));
    } else {
      test(`${label}: no github context`, !/\$\{\{\s*github\./.test(yamlBody));
      test(`${label}: uses gitea context`, /\$\{\{\s*gitea\./.test(yamlBody));
    }

    // --- Feature removal keeps the YAML valid ---
    for (const dropped of OPTIONAL_FEATURES) {
      const without = render(platform.template, { features: ["test"] });
      const withoutParsed = parseYaml(without);
      test(`${label}: valid YAML without ${dropped}`, withoutParsed.ok, withoutParsed.error);
      if (!withoutParsed.ok) continue;

      const withoutNames = stepNames(withoutParsed.data);
      test(`${label}: ${dropped} step removed`, !withoutNames.some(n => new RegExp(dropped, "i").test(n)),
        withoutNames.join(", "));
      test(`${label}: test report still present without ${dropped}`,
        withoutNames.some(n => /test report/i.test(n)));
    }

    // --- Each feature toggled on alone ---
    // The artifact step is named "Upload JAR"; identify it by its artifact
    // name rather than by the feature keyword.
    const featureMarker = {
      coverage: n => /coverage/i.test(n),
      spotbugs: n => /spotbugs/i.test(n),
      artifact: n => /upload jar/i.test(n),
    };

    for (const feature of OPTIONAL_FEATURES) {
      const withFeature = render(platform.template, { features: ["test", feature] });
      const featureParsed = parseYaml(withFeature);
      test(`${label}: valid YAML with only ${feature}`, featureParsed.ok, featureParsed.error);
      if (!featureParsed.ok) continue;
      const featureNames = stepNames(featureParsed.data);
      test(`${label}: ${feature} included when requested`,
        featureNames.some(featureMarker[feature]),
        featureNames.join(", "));
    }
  }
}

// ============================================================
// Settings template
// ============================================================
function testSettingsTemplate() {
  section("Maven Settings Template");

  const relative = path.join("shared", "settings.xml.tmpl");
  const rendered = render(relative, { features: [] });

  test("settings: no unresolved placeholders", unresolvedPlaceholders(rendered).length === 0,
    unresolvedPlaceholders(rendered).join(", "));

  const parsed = parseXml(rendered);
  test("settings: XML parses", parsed.ok, parsed.error);
  if (parsed.ok) {
    test("settings: root element is <settings>", parsed.root.tag === "settings", parsed.root.tag);
  }

  test("settings: defines a mirror", rendered.includes("<mirrors>") && rendered.includes("<mirrorOf>*</mirrorOf>"));
  test("settings: mirror id substituted", rendered.includes(FIXTURE_VALUES["{MIRROR_ID}"]));
  test("settings: mirror url substituted", rendered.includes(FIXTURE_VALUES["{MIRROR_URL}"]));
  // The template mentions <localRepository> inside an XML comment; only the
  // element itself would change Maven's local repository.
  const settingsBody = rendered.replace(/<!--[\s\S]*?-->/g, "");
  test("settings: no custom localRepository", !/<localRepository>/.test(settingsBody),
    "A custom localRepository must be paired with a matching cache path");
  test("settings: warns about cache coupling", rendered.includes("localRepository"));
}

// ============================================================
// Placeholder contract
// ============================================================
function testPlaceholderContract() {
  section("Placeholder Contract");

  const skillPath = path.join(TEMPLATES_ROOT, "..", "SKILL.md");
  if (!fs.existsSync(skillPath)) {
    test("ci-setup SKILL.md exists", false);
    return;
  }
  const skill = fs.readFileSync(skillPath, "utf8");

  const workflowPlaceholders = [
    "{VERSION}", "{BRANCHES}", "{PR_BRANCHES}", "{JAVA_VERSION}", "{RUNNER}",
    "{MAVEN_CMD}", "{MAVEN_ARGS}", "{CACHE_PATH}", "{ARTIFACT_GLOB}",
  ];
  const settingsPlaceholders = ["{VERSION}", "{MIRROR_ID}", "{MIRROR_NAME}", "{MIRROR_URL}"];

  for (const placeholder of [...workflowPlaceholders, ...settingsPlaceholders]) {
    test(`SKILL.md documents ${placeholder}`, skill.includes(placeholder));
  }

  // Every placeholder used in a template must be documented in the skill.
  for (const platform of PLATFORMS) {
    const raw = fs.readFileSync(path.join(TEMPLATES_ROOT, platform.template), "utf8");
    const used = raw.match(/\{[A-Z_]+\}/g) || [];
    const undocumented = Array.from(new Set(used)).filter(p => !workflowPlaceholders.includes(p));
    test(`${platform.id}: all placeholders documented`, undocumented.length === 0, undocumented.join(", "));
  }

  const rawSettings = fs.readFileSync(path.join(TEMPLATES_ROOT, "shared", "settings.xml.tmpl"), "utf8");
  const usedSettings = rawSettings.match(/\{[A-Z_]+\}/g) || [];
  const undocumentedSettings = Array.from(new Set(usedSettings)).filter(p => !settingsPlaceholders.includes(p));
  test("settings: all placeholders documented", undocumentedSettings.length === 0, undocumentedSettings.join(", "));
}

// ============================================================
// Run
// ============================================================
console.log("+" + "=".repeat(58) + "+");
console.log("|   spring-boot-workflows — CI Template Golden Test          |");
console.log("+" + "=".repeat(58) + "+");

testRenderedWorkflows();
testSettingsTemplate();
testPlaceholderContract();

console.log(`\n${"=".repeat(60)}`);
console.log("  RESULTS");
console.log("=".repeat(60));
console.log(`  Total:   ${total}`);
console.log(`  Passed:  ${passed}`);
console.log(`  Skipped: ${skipped}`);
console.log(`  Failed:  ${failed}`);
console.log();

if (failures.length > 0) {
  console.log("  FAILURES:");
  for (const f of failures) {
    console.log(`    x ${f.name}`);
    if (f.detail) console.log(`      ${f.detail}`);
  }
  console.log();
}

if (failed > 0) {
  console.log(`  ${failed} TEST(S) FAILED`);
  console.log();
  process.exit(1);
}

console.log("  ALL TESTS PASSED");
console.log();
